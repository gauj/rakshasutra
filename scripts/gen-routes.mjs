// One-off generator for packages/core/src/routes.ts: real driving routes between the places in the "schoolday" demo
// (a generic home in Prosper, Liberty High School, and the Frisco ISD CTE Center), fetched once from the free OSRM
// demo server and thinned to a few dozen points each, so the demo needs no network at run time.
//
//   node scripts/gen-routes.mjs

import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

// Public places, and a generic home in Prosper (not any real family's address).
const HOME = { lat: 33.2235, lon: -96.77 }; // generic: just off US 380 in Prosper, not any family's address
const SCHOOL = { lat: 33.1392207, lon: -96.7423851 }; // Liberty High School, Rolater Road, Frisco
const CTE = { lat: 33.1265302, lon: -96.7960168 }; // Frisco ISD Career and Technical Education Center, Wade Boulevard

const R = 6371000;
const rad = (d) => (d * Math.PI) / 180;
const dist = (a, b) => {
  const x = rad(b.lat - a.lat);
  const y = rad(b.lon - a.lon);
  const h = Math.sin(x / 2) ** 2 + Math.cos(rad(a.lat)) * Math.cos(rad(b.lat)) * Math.sin(y / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(h));
};

// Ramer-Douglas-Peucker thinning, using a flat-earth distance to the chord (fine at this scale).
function thin(pts, tolM) {
  const keep = new Array(pts.length).fill(false);
  keep[0] = keep[pts.length - 1] = true;
  const k = Math.cos(rad(pts[0].lat));
  const xy = (p) => [p.lon * 111320 * k, p.lat * 110540];
  const rec = (i, j) => {
    const [ax, ay] = xy(pts[i]);
    const [bx, by] = xy(pts[j]);
    const L = Math.hypot(bx - ax, by - ay) || 1;
    let max = 0;
    let at = -1;
    for (let m = i + 1; m < j; m++) {
      const [px, py] = xy(pts[m]);
      const d = Math.abs((by - ay) * (px - ax) - (bx - ax) * (py - ay)) / L;
      if (d > max) {
        max = d;
        at = m;
      }
    }
    if (max > tolM && at > 0) {
      keep[at] = true;
      rec(i, at);
      rec(at, j);
    }
  };
  rec(0, pts.length - 1);
  return pts.filter((_, i) => keep[i]);
}

async function route(a, b) {
  const url = `https://router.project-osrm.org/route/v1/driving/${a.lon},${a.lat};${b.lon},${b.lat}?overview=full&geometries=geojson`;
  const d = await (await fetch(url, { signal: AbortSignal.timeout(30000) })).json();
  const line = d.routes[0].geometry.coordinates.map(([lon, lat]) => ({ lat, lon }));
  return thin(line, 6);
}

const legs = {
  HOME_TO_SCHOOL: await route(HOME, SCHOOL),
  SCHOOL_TO_CTE: await route(SCHOOL, CTE),
};
legs.CTE_TO_SCHOOL = [...legs.SCHOOL_TO_CTE].reverse();
legs.SCHOOL_TO_HOME = [...legs.HOME_TO_SCHOOL].reverse();
// The home sits exactly on the road where the trip starts, so the child does not jump from the house to the road.
const HOME_ON_ROAD = legs.HOME_TO_SCHOOL[0];

const fmt = (l) => "[" + l.map((p) => `{ lat: ${p.lat.toFixed(5)}, lon: ${p.lon.toFixed(5)} }`).join(", ") + "]";
let out = `// Generated by scripts/gen-routes.mjs: real driving routes between the places in the "schoolday" demo.
// Public places (Liberty High School, the Frisco ISD CTE Center) and a generic home in Prosper; no family's address.
// Roads © OpenStreetMap contributors, routed once with OSRM.
import type { LatLon } from "./geo.js";

export const SCHOOLDAY_PLACES: { home: LatLon; school: LatLon; cte: LatLon } = {
  home: ${JSON.stringify({ lat: +HOME_ON_ROAD.lat.toFixed(5), lon: +HOME_ON_ROAD.lon.toFixed(5) })},
  school: ${JSON.stringify(SCHOOL)},
  cte: ${JSON.stringify(CTE)},
};

`;
for (const [name, l] of Object.entries(legs)) {
  const len = l.slice(1).reduce((s, p, i) => s + dist(l[i], p), 0);
  out += `/** About ${(len / 1000).toFixed(1)} km, ${l.length} points. */\nexport const ROUTE_${name}: LatLon[] = ${fmt(l)};\n\n`;
  console.log(name, l.length, "points,", (len / 1000).toFixed(1), "km");
}
writeFileSync(path.join(root, "packages", "core", "src", "routes.ts"), out);
console.log("wrote packages/core/src/routes.ts");
